/**
 * 工具函数：计算环比增速（%）
 * @param {number[]} values 单月值数组
 * @returns {(number|null)[]} 环比增速数组，首项为null
 */
window.calcMoM = function (values) {
  if (!values || values.length === 0) return [];
  var mom = [null];
  for (var i = 1; i < values.length; i++) {
    if (values[i - 1] && values[i - 1] !== 0) {
      mom.push(+(((values[i] - values[i - 1]) / Math.abs(values[i - 1])) * 100).toFixed(1));
    } else {
      mom.push(null);
    }
  }
  return mom;
};
